const i18n = {
  lang: "en",
  t(key, vars = {}) {
    const text = translations[i18n.lang][key] ?? translations.en[key] ?? key;
    return Object.entries(vars).reduce((acc, [name, value]) => acc.replaceAll(`{${name}}`, value), text);
  },
  apply() {
    document.documentElement.lang = i18n.lang === "pt" ? "pt-BR" : "en";
    document.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = i18n.t(node.dataset.i18n); });
    document.querySelectorAll("[data-lang]").forEach((button) => button.classList.toggle("active", button.dataset.lang === i18n.lang));
  },
  set(lang) {
    i18n.lang = translations[lang] ? lang : "en";
    try { localStorage.setItem("gm.lang", i18n.lang); } catch {}
    i18n.apply();
    document.dispatchEvent(new CustomEvent("langchange"));
  },
  init() {
    let saved = null;
    try { saved = localStorage.getItem("gm.lang"); } catch {}
    const detected = navigator.language?.toLowerCase().startsWith("pt") ? "pt" : "en";
    i18n.lang = saved ?? detected;
    i18n.apply();
  }
};
